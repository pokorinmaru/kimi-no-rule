// M2: EVALS.md, generated from the eval results (指示書 第10節). Deterministic: the same input gives the
// same text (no clock, no random order). Systems that did not run are listed with the reason.
import type { InterpretRow, SafetyRow } from "./dataset.ts";
import { lostToBaseline, type Rate, type SystemResult } from "./interpret-eval.ts";
import type { SafetyResult } from "./safety-eval.ts";

export interface NotRun {
  name: string;
  reason: string;
}

export interface EvalsInput {
  interpret: { k: number; baseline: string; results: SystemResult[]; notRun: NotRun[] };
  safety: { results: { name: string; result: SafetyResult }[]; notRun: NotRun[] };
  data: { interpret: readonly InterpretRow[]; safety: readonly SafetyRow[] };
  /** A heading note, e.g. which problem set the rows come from. */
  note?: string;
}

const pct = (x: number): string => `${(x * 100).toFixed(1)}%`;
const rateCell = (r: Rate): string => (r.n === 0 ? "—" : `${r.k}/${r.n} (${pct(r.k / r.n)}; 95% CI ${pct(r.low)}–${pct(r.high)})`);
const cell = (s: string): string => s.replaceAll("|", "\\|").replaceAll("\n", " ");

function counts<T>(rows: readonly T[], key: (r: T) => string): [string, number][] {
  const m = new Map<string, number>();
  for (const r of rows) m.set(key(r), (m.get(key(r)) ?? 0) + 1);
  return [...m].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
}

function countTable(title: string, rows: [string, number][]): string[] {
  return [`| ${title} | rows |`, "| --- | --- |", ...rows.map(([k, n]) => `| ${cell(k)} | ${n} |`), ""];
}

export function renderEvalsMd(input: EvalsInput): string {
  const out: string[] = [
    "<!-- generated by tools/evals (pnpm eval / pnpm eval:live); do not edit by hand -->",
    "# EVALS",
    "",
    "評価の取り決めは EVALS-PROTOCOL.md（調整より前に凍結）。一致率の区間はウィルソンの方法、取りこぼしの上限は Clopper-Pearson の片側95%。",
    "",
  ];
  if (input.note !== undefined) out.push(input.note, "");

  out.push("## 解釈の評価（聞く層）", "", `各行を k=${input.interpret.k} 回聞いた。世界の一致・層の一致は1回目、pass^k は k 回すべて一致した行。`, "");
  out.push("層の一致（層のある行）は、期待の読みに層がある行だけで数えたもの。何も言わない返事は、層の無い行では層が一致してしまうため。", "");
  out.push("| system | 世界の一致 | 層の一致 | 層の一致（層のある行） | pass^k | 遅延 中央値 / p95 (ms) |", "| --- | --- | --- | --- | --- | --- |");
  for (const r of input.interpret.results) {
    const lat = r.latency === null ? "—" : `${r.latency.median} / ${r.latency.p95}`;
    out.push(`| ${cell(r.name)} | ${rateCell(r.worldMatch)} | ${rateCell(r.layerMatch)} | ${rateCell(r.layeredMatch)} | ${rateCell(r.passAllK)} | ${lat} |`);
  }
  for (const n of input.interpret.notRun) out.push(`| ${cell(n.name)} | 未実行：${cell(n.reason)} | | | | |`);
  out.push("");

  const ran = input.interpret.results.some((r) => r.name === input.interpret.baseline);
  if (ran) {
    out.push(`### キーワード規則（${cell(input.interpret.baseline)}）に負けた行`, "");
    const lost = lostToBaseline(input.interpret.results, input.interpret.baseline);
    if (Object.keys(lost).length === 0) out.push("比べる相手がまだ回っていない。");
    for (const [name, ids] of Object.entries(lost).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
      out.push(`- ${cell(name)}: ${ids.length === 0 ? "なし" : ids.join(", ")}`);
    }
    out.push("");
  }

  out.push(
    "## 安全の評価",
    "",
    "端末の辞書は、何も見つからない時に「なし」とは言わず「確かめられなかった」を返す（画面は止める・わからない・つらいの札をやさしく出す）。表ではそれを検出に数えない。Claude の列は Claude が答えた回の性能で、実際の取りこぼしはおよそ「Claude の取りこぼし＋失敗の率×辞書の取りこぼし」になる。",
    "",
  );
  out.push("| check | distress の検出 | 取りこぼし | 取りこぼし率の上限 (片側95%) | 誤検知（none の行） | 不適切の検出 |", "| --- | --- | --- | --- | --- | --- |");
  for (const { name, result } of input.safety.results) {
    out.push(
      `| ${cell(name)} | ${rateCell(result.recall)} | ${result.misses.length === 0 ? "なし" : result.misses.join(", ")} | ${pct(result.missUpper)} (${result.missUpper.toFixed(3)}) | ${rateCell(result.falseAlarms)}${result.falseAlarms.ids.length === 0 ? "" : ` ${result.falseAlarms.ids.join(", ")}`} | ${rateCell(result.inappropriate)} |`,
    );
  }
  for (const n of input.safety.notRun) out.push(`| ${cell(n.name)} | 未実行：${cell(n.reason)} | | | | |`);
  out.push("");

  out.push("## データ", "", "### 解釈", "");
  out.push(...countTable("split", counts(input.data.interpret, (r) => r.split)));
  out.push(...countTable("kind", counts(input.data.interpret, (r) => r.kind)));
  out.push(...countTable("source", counts(input.data.interpret, (r) => r.source)));
  out.push("### 安全", "");
  out.push(...countTable("split", counts(input.data.safety, (r) => r.split)));
  out.push(...countTable("expected / style", counts(input.data.safety, (r) => `${r.expected} / ${r.style}`)));
  out.push(...countTable("source", counts(input.data.safety, (r) => r.source)));
  return `${out.join("\n").trimEnd()}\n`;
}
