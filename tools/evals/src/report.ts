// M2: EVALS.md, generated from the eval results (指示書 第10節). Deterministic: the same input gives the
// same text (no clock, no random order). Systems that did not run are listed with the reason.
import type { InterpretRow, SafetyRow } from "./dataset.ts";
import { lostToBaseline, type Rate, type SystemResult } from "./interpret-eval.ts";
import type { LeakResult } from "./kohai-eval.ts";
import type { LeakJudgeResult } from "./leak-judge.ts";
import type { ResearchResult } from "./research-eval.ts";
import type { ResearchJudgeResult } from "./research-judge.ts";
import type { SafetyResult } from "./safety-eval.ts";
import { wilson } from "./stats.ts";

export interface NotRun {
  name: string;
  reason: string;
}

export interface EvalsInput {
  interpret: { k: number; baseline: string; results: SystemResult[]; notRun: NotRun[] };
  safety: { results: { name: string; result: SafetyResult }[]; notRun: NotRun[] };
  data: { interpret: readonly InterpretRow[]; safety: readonly SafetyRow[] };
  /** The research eval (simulated children), when it was run. */
  research?: { results: ResearchResult[]; notRun: NotRun[]; seeds: number; maxProblems: number; seedsBySystem?: Record<string, number> };
  /** The research eval with recovered judged again on the judging problems (addendum 5), when it was run. */
  researchJudge?: { results: ResearchJudgeResult[]; notRun: NotRun[]; maxProblems: number; bankProblems: number; judgeProblems: number };
  /** The junior's lines judged by a model next to core's gate (addendum 5), when it was run. */
  leakJudge?: { results: LeakJudgeResult[]; notRun: NotRun[]; rows: number; k: number; thirdParty?: LeakJudgeResult[] };
  /** The junior's-words leak comparison, when it was run. */
  leak?: { results: LeakResult[]; notRun: NotRun[]; rows: number; k: number };
  /** A heading note, e.g. which problem set the rows come from. */
  note?: string;
  /** Which run each section's numbers come from (sections can come from different runs). */
  sources?: { section: string; from: string }[];
  /**
   * Rows written by a third-party adult (指示書 第10.1節・第10.3節), run like the AI drafts and shown as their
   * own rows, never added into the AI-draft numbers. Absent, or both null: one line says there are none yet.
   */
  thirdParty?: {
    safety: { rows: number; results: { name: string; result: SafetyResult }[] } | null;
    leak: { rows: number; results: LeakResult[] } | null;
  };
}

/** The suffix that names a row computed on third-party rows only. */
export const THIRD_PARTY_SUFFIX = "（第三者の行）";
export const NO_THIRD_PARTY = "第三者が書いた行はまだ無い（数字はすべて AI の下書きの行。足し方は evals/third-party/README.md）。";

const pct = (x: number): string => `${(x * 100).toFixed(1)}%`;
const rateCell = (r: Rate): string => (r.n === 0 ? "—" : `${r.k}/${r.n} (${pct(r.k / r.n)}; 95% CI ${pct(r.low)}–${pct(r.high)})`);
const cell = (s: string): string => s.replaceAll("|", "\\|").replaceAll("\n", " ");

function counts<T>(rows: readonly T[], key: (r: T) => string): [string, number][] {
  const m = new Map<string, number>();
  for (const r of rows) m.set(key(r), (m.get(key(r)) ?? 0) + 1);
  return [...m].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
}

function countTable(title: string, rows: [string, number][]): string[] {
  return [`| ${title} | rows |`, "| --- | --- |", ...rows.map(([k, n]) => `| ${cell(k)} | ${n} |`), ""];
}

export function renderEvalsMd(input: EvalsInput): string {
  const out: string[] = [
    "<!-- generated by tools/evals (pnpm eval / pnpm eval:live); do not edit by hand -->",
    "# EVALS",
    "",
    "評価の取り決めは EVALS-PROTOCOL.md（調整より前に凍結）。一致率の区間はウィルソンの方法、取りこぼしの上限は Clopper-Pearson の片側95%。",
    "",
  ];
  if (input.note !== undefined) out.push(input.note, "");
  if (input.sources !== undefined && input.sources.length > 0) {
    out.push("数字の出どころ（節ごとに別の実行から来ることがある。実行 id は evals/results/ のフォルダ名）：", "");
    for (const s of input.sources) out.push(`- ${s.section}：${s.from}`);
    out.push("");
  }
  const tp = input.thirdParty;
  if (tp === undefined || (tp.safety === null && tp.leak === null)) out.push(NO_THIRD_PARTY, "");
  else {
    const parts = [tp.safety === null ? null : `安全 ${tp.safety.rows} 行`, tp.leak === null ? null : `後輩の言葉 ${tp.leak.rows} 行`].filter((x) => x !== null);
    out.push(`第三者が書いた行（${parts.join("、")}）は、名前に「${THIRD_PARTY_SUFFIX}」を付けた別の行に出す。AI の下書きの行の数字には足していない。`, "");
  }

  if (input.leak !== undefined) out.push(...leakSection(input.leak, tp?.leak?.results ?? []));
  if (input.leakJudge !== undefined) out.push(...leakJudgeSection(input.leakJudge));

  out.push("## 解釈の評価（聞く層）", "", `各行を k=${input.interpret.k} 回聞いた。世界の一致・層の一致は1回目、pass^k は k 回すべて一致した行。`, "");
  out.push("層の一致（層のある行）は、期待の読みに層がある行だけで数えたもの。何も言わない返事は、層の無い行では層が一致してしまうため。", "");
  out.push("| system | 世界の一致 | 層の一致 | 層の一致（層のある行） | pass^k | 遅延 中央値 / p95 (ms) |", "| --- | --- | --- | --- | --- | --- |");
  for (const r of input.interpret.results) {
    const lat = r.latency === null ? "—" : `${r.latency.median} / ${r.latency.p95}`;
    out.push(`| ${cell(r.name)} | ${rateCell(r.worldMatch)} | ${rateCell(r.layerMatch)} | ${rateCell(r.layeredMatch)} | ${rateCell(r.passAllK)} | ${lat} |`);
  }
  for (const n of input.interpret.notRun) out.push(`| ${cell(n.name)} | 未実行：${cell(n.reason)} | | | | |`);
  out.push("");

  const ran = input.interpret.results.some((r) => r.name === input.interpret.baseline);
  if (ran) {
    out.push(`### キーワード規則（${cell(input.interpret.baseline)}）に負けた行`, "");
    const lost = lostToBaseline(input.interpret.results, input.interpret.baseline);
    if (Object.keys(lost).length === 0) out.push("比べる相手がまだ回っていない。");
    for (const [name, ids] of Object.entries(lost).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
      out.push(`- ${cell(name)}: ${ids.length === 0 ? "なし" : ids.join(", ")}`);
    }
    out.push("");
  }

  out.push(
    "## 安全の評価",
    "",
    "端末の辞書は、何も見つからない時に「なし」とは言わず「確かめられなかった」を返す（画面は止める・わからない・つらいの札をやさしく出す）。表ではそれを検出に数えず、none の行では誤検知に数える（辞書だけの列の誤検知が 100% なのはこのため。画面は止めずに札を出すだけ）。Claude の列は Claude が答えた回の性能で、実際の取りこぼしはおよそ「Claude の取りこぼし＋失敗の率×辞書の取りこぼし」になる。",
    "",
  );
  out.push("| check | distress の検出 | 取りこぼし | 取りこぼし率の上限 (片側95%) | 誤検知（none の行） | 不適切の検出 |", "| --- | --- | --- | --- | --- | --- |");
  for (const { name, result } of [...input.safety.results, ...(tp?.safety?.results ?? []).map((r) => ({ ...r, name: `${r.name}${THIRD_PARTY_SUFFIX}` }))]) {
    out.push(
      `| ${cell(name)} | ${rateCell(result.recall)} | ${result.misses.length === 0 ? "なし" : result.misses.join(", ")} | ${pct(result.missUpper)} (${result.missUpper.toFixed(3)}) | ${rateCell(result.falseAlarms)}${result.falseAlarms.ids.length === 0 ? "" : ` ${result.falseAlarms.ids.join(", ")}`} | ${rateCell(result.inappropriate)} |`,
    );
  }
  for (const n of input.safety.notRun) out.push(`| ${cell(n.name)} | 未実行：${cell(n.reason)} | | | | |`);
  out.push("");

  if (input.research !== undefined) out.push(...researchSection(input.research));
  if (input.researchJudge !== undefined) out.push(...researchJudgeSection(input.researchJudge));

  out.push("## データ", "", "### 解釈", "");
  out.push(...countTable("split", counts(input.data.interpret, (r) => r.split)));
  out.push(...countTable("kind", counts(input.data.interpret, (r) => r.kind)));
  out.push(...countTable("source", counts(input.data.interpret, (r) => r.source)));
  out.push("### 安全", "");
  out.push(...countTable("split", counts(input.data.safety, (r) => r.split)));
  out.push(...countTable("expected / style", counts(input.data.safety, (r) => `${r.expected} / ${r.style}`)));
  out.push(...countTable("source", counts(input.data.safety, (r) => r.source)));
  return `${out.join("\n").trimEnd()}\n`;
}

const KIND_LABEL: [keyof ResearchResult["byKind"], string][] = [
  ["listed", "よくある読み違いの一覧にある読み方"],
  ["inside", "一覧に無く、列挙の範囲の内側"],
  ["outside", "一覧に無く、列挙の範囲の外側"],
  ["inexpressible", "記述言語で書けない読み方"],
];

const ratio = (k: number, n: number): string => {
  if (n === 0) return "—";
  const ci = wilson(k, n);
  return `${k}/${n} (${pct(k / n)}; 95% CI ${pct(ci.low)}–${pct(ci.high)})`;
};

function researchSection(r: NonNullable<EvalsInput["research"]>): string[] {
  const out: string[] = [
    "## 読み方の研究の評価（研究する層）",
    "",
    `読み方を先に決めた模擬の子どもに、1問目は看板の問題、その後は研究する側が選んだ問題を最大 ${r.maxProblems} 問まで出した（1人の子どもにつき表の「回数」の回だけ。うっかりの率と並びは種で固定）。確定した読み方が、銀行のすべての問題で子どもの読み方と同じ世界を作れば「回復」。確定したのに回復でなければ「誤った確定」。記述言語で書けない読み方は、回復ではなく誤った確定の率を見る。`,
    "",
    "模擬の子どもも判定も同じ記述言語で書いているので、評価はその中で閉じている（循環）。書けない読み方の行は、その循環を一部だけ破るために置いた。模擬の子どもと言い方は AI の下書きで、第三者が書いたものではない（BLOCKED B3）。",
    "",
    "限界：(1) この節の回復は、問題を選ぶのと同じ銀行の9問で判定する。銀行で見分けられない2つの読み方は同じとみなすので、回復は甘めに出る（銀行とは別の判定用の問題で測り直した数は、追補5の節に出す。回した時だけ）。(2) Claude には子どもの言葉を渡し、基線には渡さない（言葉の照合の基線は作っていない）。列挙の外側の子どもの言葉は、手がかりの語をそのまま言うので、Claude の列の外側の行は「言葉から読んだ」ことの証拠としては弱い。(3) 研究層は1問目の読みから仮説を書くので1問目を重みに数えず、基線は1問目から数える。確定までの問題数は、研究層の側が1問ぶん不利になる。",
    "",
    "| system | 回数 | 読み方の種類 | 回復 | 誤った確定 | 確定までの問題数（回復した回の中央値） |",
    "| --- | --- | --- | --- | --- | --- |",
  ];
  for (const res of r.results) {
    const seeds = r.seedsBySystem?.[res.name] ?? r.seeds;
    for (const [kind, label] of KIND_LABEL) {
      const row = res.byKind[kind];
      const after = [...row.confirmedAfter].sort((a, b) => a - b);
      const med = after.length === 0 ? "—" : String(after[Math.floor((after.length - 1) / 2)]);
      const recovered = kind === "inexpressible" ? "—" : ratio(row.recovered, row.episodes);
      out.push(`| ${cell(res.name)} | ${seeds} | ${label} | ${recovered} | ${ratio(row.falseConfirmations, row.episodes)} | ${med} |`);
    }
  }
  for (const n of r.notRun) out.push(`| ${cell(n.name)} | 未実行：${cell(n.reason)} | | | | |`);
  out.push("");
  return out;
}

function leakSection(l: NonNullable<EvalsInput["leak"]>, thirdParty: readonly LeakResult[]): string[] {
  const out: string[] = [
    "## 後輩の言葉の漏れの比較",
    "",
    `答えを教えてと押す・答えに近い数を言う・演算を聞く・英語まじり・合っているかを聞く、の ${l.rows} 行を、各 ${l.k} 回ずつ後輩に言わせた。漏れは core の関門で判定する（答えと途中の値、演算の名前）。加えて、正誤を言う言葉も数える（「合っていますか？」と確かめる問いは数えない）。子どもが言った答えを言い返すのも漏れに数える。左は、答えと正しい世界を渡したうえで「言わないで」とプロンプトで頼んだ Claude。右は、この作品の後輩（答えを知らない＋関門、落ちたら定型文）。行は AI の下書きで、第三者が書いたものではない（BLOCKED B3）。`,
    "",
    "| junior | 漏れた発話 | 答えと途中の値 | 演算の名前 | 正誤を言う言葉 |",
    "| --- | --- | --- | --- | --- |",
  ];
  for (const r of [...l.results, ...thirdParty.map((x) => ({ ...x, name: `${x.name}${THIRD_PARTY_SUFFIX}` }))]) {
    out.push(`| ${cell(r.name)} | ${ratio(r.leaked, r.lines)} | ${r.byKind.answer_leak} | ${r.byKind.operation_name} | ${r.byKind.judging} |`);
  }
  for (const n of l.notRun) out.push(`| ${cell(n.name)} | 未実行：${cell(n.reason)} | | | |`);
  out.push("");
  return out;
}

function researchJudgeSection(r: NonNullable<EvalsInput["researchJudge"]>): string[] {
  const out: string[] = [
    "## 読み方の研究の評価（判定用の問題で回復を測り直す）",
    "",
    `上の節と同じやり方で模擬の子どもと研究する側を会わせ（最大 ${r.maxProblems} 問）、確定した読み方を2通りに判定した。「銀行」は上の節と同じく、問題を選ぶのに使う銀行の ${r.bankProblems} 問すべてで子どもの読み方と同じ世界を作れば回復。「判定用」は、銀行とは別に用意し研究する側には一度も出さない判定用の問題 ${r.judgeProblems} 問（evals/data/research/judge-problems.ts）で同じことを確かめた。2つの数は同じ回から出している。判定用の問題はこのリポジトリの作者が書いたもので、第三者が書いたものではない（追補5）。`,
    "",
    "| system | 回数 | 読み方の種類 | 回復（銀行） | 回復（判定用） | 誤った確定（銀行） | 誤った確定（判定用） |",
    "| --- | --- | --- | --- | --- | --- | --- |",
  ];
  for (const res of r.results) {
    for (const [kind, label] of KIND_LABEL) {
      const b = res.bank[kind];
      const j = res.judge[kind];
      const rec = (row: typeof b): string => (kind === "inexpressible" ? "—" : ratio(row.recovered, row.episodes));
      out.push(`| ${cell(res.name)} | ${res.seeds} | ${label} | ${rec(b)} | ${rec(j)} | ${ratio(b.falseConfirmations, b.episodes)} | ${ratio(j.falseConfirmations, j.episodes)} |`);
    }
  }
  for (const n of r.notRun) out.push(`| ${cell(n.name)} | 未実行：${cell(n.reason)} | | | | | |`);
  out.push("");
  return out;
}

function leakJudgeSection(l: NonNullable<EvalsInput["leakJudge"]>): string[] {
  const out: string[] = [
    "## 後輩の言葉を別のモデルで判定する（関門の網の粗さ）",
    "",
    `後輩の言葉の漏れの比較と同じ ${l.rows} 行を各 ${l.k} 回、後輩にもう一度言わせ（上の表とは別に生成した発話）、同じ発話を core の関門と別のモデル（haiku-5.5）の両方で判定した。モデルには問題文・答え・もとにする量を渡し、答え・途中の値・演算・正しい向きのどれかを明かしているかを聞いた。「判定だけ」は、モデルが明かしているとしたのに関門が通した発話（関門の網の粗さ）。「関門だけ」はその逆。割合の分母は、モデルが判定できた発話の数。モデルの判定は数えるだけで、子どもに見せるかどうかは決めない。人による判定（100件）はまだ（追補5）。`,
    "",
    "| junior | 発話 | 関門が落とした | 判定が漏れとした | 判定だけ（網の粗さ） | 関門だけ | 両方 | 判定できなかった | 答え | 途中の値 | 演算 | 向き |",
    "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
  ];
  for (const r of [...l.results, ...(l.thirdParty ?? []).map((x) => ({ ...x, name: `${x.name}${THIRD_PARTY_SUFFIX}` }))]) {
    const judged = r.lines - r.unjudged;
    out.push(
      `| ${cell(r.name)} | ${r.lines} | ${r.gateFlagged} | ${r.judgeFlagged} | ${ratio(r.judgeOnly, judged)} | ${ratio(r.gateOnly, judged)} | ${r.both} | ${r.unjudged} | ${r.byKind.answer} | ${r.byKind.value} | ${r.byKind.operation} | ${r.byKind.direction} |`,
    );
  }
  for (const n of l.notRun) out.push(`| ${cell(n.name)} | 未実行：${cell(n.reason)} | | | | | | | | | | |`);
  out.push("");
  return out;
}
